import cv2
import numpy as np
import matplotlib.pyplot as plt

path = 'ejemplo.jpg'
imagen = cv2.imread(path)

print ('Dimesiones', imagen.shape)
print ('Tip de dato', imagen.dtype)

imagen_rgb= cv2.cvtColor(imagen, cv2.COLOR_BGR2RGB)
plt.figure(figsize=(8,6))
plt.imshow(imagen_rgb)
plt.title ('Imagen original')
plt.axis ('off')
plt.show()

"""## 2. Conversión a Escala de Grises"""

imagen_gris = cv2.cvtColor(imagen, cv2.COLOR_BGR2GRAY)

print('Dimensiones imagen gris', imagen_gris.shape)

plt.figure(figsize=(8,6))
plt.imshow(imagen_gris, cmap='gray')
plt.title ('Imagen en escala de grises')
plt.axis ('off')
plt.show()

"""## 3. Aplicación de Filtro de Desenfoque"""

imagen_blur = cv2.GaussianBlur(imagen_gris, (5,5), 0)

plt.figure(figsize=(8,6))
plt.imshow(imagen_blur, cmap='gray')
plt.title ('Imagen con filtro de desenfoque')
plt.axis ('off')
plt.show ()

"""## 4. Detección de Bordes"""

bordes = cv2.Canny(imagen_blur, 100, 200)

plt.figure(figsize=(8,6))
plt.imshow(bordes, cmap='gray')
plt.title ('Imagen con bordes')
plt.axis ('off')
plt.show ()

"""## 5. Guardado de Imágenes Procesadas"""

cv2.imwrite ('imagen_gris.jpg', imagen_gris)
cv2.imwrite ('imagen_blur.jpg', imagen_blur)
cv2.imwrite ('imagen_bordes.jpg', bordes)

print ('Imágenes guardadas correctamente')