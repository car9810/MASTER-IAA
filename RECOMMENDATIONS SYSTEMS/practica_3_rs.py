import pandas as pd

ratings_df = pd.read_csv(
    "ml-100k/u.data",
    sep="\t",
    names=["user_id", "movie_id", "rating", "timestamp"]
)

movies_df = pd.read_csv(
    "ml-100k/u.item",
    sep="|",
    encoding="latin-1",
    header=None,
    usecols=[0, 1],
    names=["movie_id", "movie_title"]
)

print("Dataset MovieLens cargado correctamente")

display(ratings_df.head())
display(movies_df.head())

"""## 3. Preprocesar los datos"""

# Seleccionar las columnas necesarias
ratings_df = ratings_df[
    ["user_id", "movie_title", "rating"]
]

# Mostrar las primeras filas
ratings_df.head()

# Crear el dataset de TensorFlow
ratings = tf.data.Dataset.from_tensor_slices({
    "user_id": ratings_df["user_id"].astype(str).values,
    "movie_title": ratings_df["movie_title"].astype(str).values
})

# Mostrar un ejemplo
for example in ratings.take(1):
    print(example)

# Obtener los usuarios y películas únicos
user_ids = ratings_df["user_id"].astype(str).unique()
movie_titles = ratings_df["movie_title"].astype(str).unique()

# Mostrar el número de usuarios y películas
print("Número de usuarios:", len(user_ids))
print("Número de películas:", len(movie_titles))

# Mezclar los datos aleatoriamente
tf.random.set_seed(42)

shuffled = ratings.shuffle(
    len(ratings_df),
    seed=42,
    reshuffle_each_iteration=False
)

# Dividir los datos en entrenamiento y prueba
train = shuffled.take(80000)
test = shuffled.skip(80000).take(20000)

"""Se seleccionan las variables necesarias para construir el sistema de recomendación: el identificador del usuario y el título de la película. Posteriormente, los datos se transforman a un Dataset de TensorFlow, se identifican los usuarios y películas únicos y se divide el conjunto de datos en entrenamiento y prueba.

## 4. Definir el Modelo
"""

# Definir la dimensión de los embeddings
embedding_dimension = 32

# Crear el modelo de usuarios
user_model = tf.keras.Sequential([
    tf.keras.layers.StringLookup(
        vocabulary=user_ids,
        mask_token=None
    ),
    tf.keras.layers.Embedding(
        len(user_ids) + 1,
        embedding_dimension
    )
])

# Crear el modelo de películas
movie_model = tf.keras.Sequential([
    tf.keras.layers.StringLookup(
        vocabulary=movie_titles,
        mask_token=None
    ),
    tf.keras.layers.Embedding(
        len(movie_titles) + 1,
        embedding_dimension
    )
])

# Crear el dataset de películas candidatas
movies = tf.data.Dataset.from_tensor_slices(
    movie_titles
)

# Definir la tarea de recomendación
task = tfrs.tasks.Retrieval(
    metrics=tfrs.metrics.FactorizedTopK(
        candidates=movies.batch(128).map(movie_model)
    )
)

# Definir el modelo completo de recomendación
class MovieLensModel(tfrs.Model):

    def __init__(self, user_model, movie_model, task):
        super().__init__()

        self.user_model = user_model
        self.movie_model = movie_model
        self.task = task

    def compute_loss(self, features, training=False):

        # Obtener los embeddings de usuarios
        user_embeddings = self.user_model(
            features["user_id"]
        )

        # Obtener los embeddings de películas
        movie_embeddings = self.movie_model(
            features["movie_title"]
        )

        # Calcular la pérdida del modelo
        return self.task(
            user_embeddings,
            movie_embeddings
        )

"""Se definen dos modelos de embeddings, uno para representar a los usuarios y otro para representar a las películas. A continuación, se configura una tarea de recuperación mediante TensorFlow Recommenders y se crea el modelo completo que aprenderá la relación entre usuarios y películas.

## 5. Entrenar el modelo
"""

# Crear una instancia del modelo
model = MovieLensModel(
    user_model,
    movie_model,
    task
)

# Configurar el optimizador
model.compile(
    optimizer=tf.keras.optimizers.Adagrad(
        learning_rate=0.1
    )
)

# Preparar los datos de entrenamiento
cached_train = (
    train
    .shuffle(100000)
    .batch(8192)
    .cache()
)

# Preparar los datos de prueba
cached_test = (
    test
    .batch(4096)
    .cache()
)

# Entrenar el modelo durante 3 épocas
history = model.fit(
    cached_train,
    epochs=3
)

"""El modelo se configura utilizando el optimizador Adagrad y se entrena durante tres épocas con el conjunto de entrenamiento. Los datos se agrupan en lotes para facilitar el proceso de aprendizaje.

## 6. Configurar el índice para la búsqueda de recomendaciones
"""

# Crear el índice de búsqueda
index = tfrs.layers.factorized_top_k.BruteForce(
    model.user_model
)

# Añadir las películas al índice
index.index_from_dataset(
    tf.data.Dataset.zip(
        (
            movies.batch(100),
            movies.batch(100).map(model.movie_model)
        )
    )
)

"""Se crea un índice de búsqueda mediante BruteForce. Este índice permite comparar la representación de un usuario con las representaciones de las películas y recuperar aquellas que presentan una mayor afinidad.

## 7. Generar predicciones
"""

# Generar recomendaciones para un usuario concreto
scores, titles = index(
    tf.constant(["42"])
)

# Mostrar las 10 recomendaciones principales
print("Recomendaciones para el usuario 42:")

for title in titles[0, :10].numpy():
    print(title.decode("utf-8"))

# Mostrar también las puntuaciones de recomendación
for title, score in zip(
    titles[0, :10].numpy(),
    scores[0, :10].numpy()
):
    print(
        title.decode("utf-8"),
        "- Puntuación:",
        round(float(score), 3)
    )

"""Una vez configurado el índice, se generan recomendaciones para un usuario concreto. El modelo devuelve las películas con mayor puntuación de afinidad según las representaciones aprendidas durante el entrenamiento.

## Evaluación del modelo
"""

# Crear un diccionario con las películas reales de cada usuario
user_test_movies = {}

for example in test.as_numpy_iterator():
    user = example["user_id"].decode("utf-8")
    movie = example["movie_title"].decode("utf-8")

    # Añadir la película correspondiente a cada usuario
    if user not in user_test_movies:
        user_test_movies[user] = []

    user_test_movies[user].append(movie)

# Definir la función Precision@K
def precision_at_k(user_id, k=10):

    # Obtener las recomendaciones del modelo
    _, recommended_titles = index(
        tf.constant([user_id])
    )

    # Convertir los títulos a texto
    recommended = [
        title.decode("utf-8")
        for title in recommended_titles[0, :k].numpy()
    ]

    # Obtener las películas reales del usuario
    relevant = user_test_movies.get(user_id, [])

    # Calcular cuántas recomendaciones coinciden
    hits = len(
        set(recommended).intersection(set(relevant))
    )

    # Calcular Precision@K
    return hits / k

# Importar NumPy
import numpy as np

# Guardar los valores de Precision@10
precisions = []

# Evaluar los primeros 100 usuarios
for user_id in list(user_test_movies.keys())[:100]:

    precision = precision_at_k(
        user_id,
        k=10
    )

    precisions.append(precision)

# Mostrar el resultado medio
print("Precision@10:", np.mean(precisions))

"""Se obtiene un valor de Precision@10 de 0,037, lo que indica que aproximadamente el 3,7 % de las diez primeras recomendaciones generadas coinciden con películas relevantes del conjunto de prueba. Este resultado permite cuantificar la capacidad del modelo para recuperar elementos relevantes entre sus primeras recomendaciones."""

# Importar las librerías necesarias para AUC
from sklearn.metrics import roc_auc_score
import random

# Crear una lista con todas las películas
all_movies = list(movie_titles)

# Crear listas para las etiquetas y puntuaciones
y_true = []
y_scores = []

# Utilizar una muestra de 1000 ejemplos del conjunto de prueba
test_examples = list(
    test.take(1000).as_numpy_iterator()
)

for example in test_examples:

    # Obtener el usuario y la película real
    user_id = example["user_id"]
    positive_movie = example["movie_title"]

    # Obtener el embedding del usuario
    user_embedding = model.user_model(
        tf.expand_dims(user_id, axis=0)
    )

    # Obtener el embedding de la película real
    positive_embedding = model.movie_model(
        tf.expand_dims(positive_movie, axis=0)
    )

    # Calcular la puntuación de la película real
    positive_score = tf.reduce_sum(
        user_embedding * positive_embedding,
        axis=1
    ).numpy()[0]

    # Guardar como ejemplo positivo
    y_true.append(1)
    y_scores.append(positive_score)

    # Seleccionar una película aleatoria como ejemplo negativo
    random_movie = random.choice(all_movies)

    # Obtener el embedding de la película negativa
    negative_embedding = model.movie_model(
        tf.constant([random_movie])
    )

    # Calcular la puntuación de la película negativa
    negative_score = tf.reduce_sum(
        user_embedding * negative_embedding,
        axis=1
    ).numpy()[0]

    # Guardar como ejemplo negativo
    y_true.append(0)
    y_scores.append(negative_score)

# Calcular el valor AUC
auc = roc_auc_score(
    y_true,
    y_scores
)

# Mostrar el resultado
print("AUC:", auc)

"""Se obtiene un valor AUC de 0,7494, lo que indica que el modelo presenta una capacidad adecuada para diferenciar entre películas relevantes y no relevantes. Al encontrarse claramente por encima de 0,5, el sistema ha aprendido patrones útiles para generar recomendaciones."""